import { canonicalJson } from '../../../services/agentica/sdk/agentica-host.mjs';
import { storedBytes } from '../accounting';

const identity = 'x'.repeat(128), uuid = '00000000-0000-4000-8000-000000000000';
const revision = Number.MAX_SAFE_INTEGER;

/** Complete retained row plus store/key wrapper; valueBytes is encoded JSON, not a string length. */
export function preparationRecordBytes(keyLength: number, valueBytes: number, indexLengths: number[] = []) {
  return storedBytes('records', [identity, uuid], { generation: identity, gameId: identity, id: uuid,
    area: 'world', key: 'k'.repeat(keyLength), indexes: indexLengths.map(n => 'i'.repeat(n)), revision, value: null }) + valueBytes - 4;
}

/** Includes the duplicated witness and its JSON escaping. Only persisted UUID references are generated by these writers. */
export function preparationNodeBytes(prefixLength: number, children: number) {
  const alphabet = children <= 36 ? '0123456789abcdefghijklmnopqrstuvwxyz'
    : Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('');
  const edges = Object.fromEntries(alphabet.slice(0, children).split('').map((key, i) =>
    [key, `${String(i).padStart(8, '0')}-0000-4000-8000-000000000000`]));
  const body = { id: uuid, prefix: 'k'.repeat(prefixLength), children: edges, value: uuid };
  return storedBytes('nodes', [identity, uuid], { generation: identity, gameId: identity,
    node: { ...body, witness: canonicalJson(body) } });
}

export interface PreparationKeys { count: number; length: number; variablePositions: number; localBranches?: number }

export function preparationPathsBytes(keys: PreparationKeys[]) {
  return keys.reduce((sum, key) => sum + key.count * (
    preparationNodeBytes(key.length, 0) + key.variablePositions * preparationNodeBytes(key.length, 11)
    + (key.localBranches ?? 0) * preparationNodeBytes(key.length, 3)), 0);
}

/** Five row-coordinate paths are shared by the five columns in each neighborhood row. */
export function preparationBucketNodes(keyLength: number, coordinateDigits: number, rooms: number) {
  // Across the whole floor: <=4N room, 2(N-1) passage and 6(N-1) reservation buckets.
  // Empty, previously occupied buckets remain included. A compressed trie on B keys has
  // <=2B-1 nodes and <=2B-2 edges, even when a value is also a prefix of another key.
  const population = 12 * rooms - 8, branches = 30 * (coordinateDigits + 2);
  const nodes = Math.min(25 + branches, 2 * population - 1);
  const edges = Math.min(11 * branches, 2 * population - 2);
  const edgeBytes = preparationNodeBytes(keyLength, 2) - preparationNodeBytes(keyLength, 1);
  return nodes * preparationNodeBytes(keyLength, 0) + edges * edgeBytes;
}

/** Union-of-changed-paths bound, not one charge for every transient tree mutation. */
export function preparationTreeBytes(levelDigits: number, keys: PreparationKeys[]) {
  // <=32 static namespace/family forks. Seven floor-number paths plus the upper-floor
  // stairs path have <=levelDigits decimal branch points each (see the source-bound report).
  const shared = (32 + 8 * levelDigits) * preparationNodeBytes(64 + 2 * levelDigits, 12);
  return shared + preparationPathsBytes(keys);
}

/** Proposed hookup contract, not an existing ledger: one <=4KiB, unindexed anchor at a
 * <=96-character non-escaping ASCII key. All 95 branches are charged on its entire
 * possible execution-tree path, including unrelated existing execution entries.
 * One additional birth receipt uses the existing complete stored-row ceiling. */
export function preparationAllocationBytes() {
  const keyLength = 96, pathLength = keyLength + 7;
  return preparationRecordBytes(keyLength, 4096) + 4 // "execution" versus "world"
    + (pathLength + 1) * preparationNodeBytes(pathLength, 95) + 128 * 1024;
}
