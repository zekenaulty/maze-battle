import { presentDirectedMemory } from '../../domain/directed/memoryContext';
import { presentSourceContext } from '../../domain/directed/sourcePresentation';
import { contextSelection } from './contextSelection';
import { DIRECTED_LIMITS, DIRECTED_VERSION, type KnowledgeProjection, type ObservationReceipt, type PresentedContext, type WorldEvent } from '../../domain/directed/types';
import { address, operation, request } from './requestValidation';
import { check, id, integer, keys, list, object, same, serializable, text, utf8Bytes } from './values';

export function event(value: unknown, current: DirectedSession): asserts value is WorldEvent {
  serializable(value); object(value); keys(value, ['id', 'revision', 'type', 'subjectId'], ['position', 'before', 'after']);
  id(value.id); id(value.subjectId); integer(value.revision);
  check(value.revision > 0 && value.revision <= current.world.revision, 'invalid event revision');
  check(['move', 'interact', 'fixture-change'].includes(value.type as string), 'invalid event type');
  if (value.position !== undefined) address(value.position);
  if (value.before !== undefined) text(value.before);
  if (value.after !== undefined) text(value.after);
}
export function context(value: unknown, current: DirectedSession): asserts value is PresentedContext {
  serializable(value, DIRECTED_LIMITS.bytes * 2); object(value);
  keys(value, ['id', 'observerId', 'knowledgeRevision', 'purpose', 'observationIds', 'json', 'bytes'], ['selection']);
  if (value.selection !== undefined) contextSelection(value.selection);
  id(value.id); integer(value.knowledgeRevision); integer(value.bytes, DIRECTED_LIMITS.bytes);
  check(value.observerId === current.actor.id && value.knowledgeRevision <= current.knowledge.revision, 'context scope mismatch');
  check(value.purpose === 'human-view' || value.purpose === 'decision-fixture', 'invalid context purpose');
  list(value.observationIds, DIRECTED_LIMITS.history); value.observationIds.forEach(id);
  check(new Set(value.observationIds).size === value.observationIds.length, 'duplicate context evidence');
  check(typeof value.json === 'string' && utf8Bytes(value.json) === value.bytes, 'context byte mismatch');
  const body: unknown = JSON.parse(value.json);
  object(body);
  const version = value.selection?.kind === 'sources' ? 'directed-sources-v1' : value.selection ? 'directed-memory-v1' : DIRECTED_VERSION;
  check(body.version === version && body.worldId === current.world.id && body.floorId === current.world.floorId
    && body.observerId === value.observerId && body.knowledgeRevision === value.knowledgeRevision, 'presented context envelope mismatch');
}
/** Comparison only. Never substitute regenerated bytes for an archived response. */
export function contextFromSource(value: PresentedContext, knowledge: KnowledgeProjection, source: ObservationReceipt, floorId: string,
  sources: ObservationReceipt[] = []) {
  check(value.knowledgeRevision === knowledge.revision && source.sequence === knowledge.revision
    && source.worldId === knowledge.worldId && source.observerId === knowledge.observerId, 'context historical source mismatch');
  // Only stable scope identifiers come from the save; all facts and position are historical.
  const historical: DirectedSession = {
    version: DIRECTED_VERSION, revision: 0, epoch: 0,
    world: { id: knowledge.worldId, floorId, revision: source.sourceWorldRevision, spaces: {}, cells: {}, features: {} },
    actor: { id: source.observerId, position: structuredClone(source.scene.position) }, knowledge,
  };
  context(value, historical);
  const expected = value.selection?.kind === 'sources' ? presentSourceContext({ worldId: knowledge.worldId, floorId,
    observerId: knowledge.observerId }, knowledge.revision, value.id, value.purpose, value.selection, sources)
    : value.selection ? presentDirectedMemory(historical, value.id, value.purpose, value.selection)
    : presentDirected(historical, value.id, value.purpose);
  let expectedJson = expected.json;
  const body = JSON.parse(value.json);
  const expectedBody = JSON.parse(expected.json);
  // Additive v1 compatibility: omission is legal only for an empty historical set.
  if (!Object.hasOwn(body, 'blockedEdges') && Array.isArray(expectedBody.blockedEdges) && expectedBody.blockedEdges.length === 0) {
    const { blockedEdges: _empty, ...legacy } = expectedBody;
    expectedJson = JSON.stringify(legacy);
  }
  check(value.json === expectedJson && value.bytes === utf8Bytes(expectedJson) && same(value.observationIds, expected.observationIds),
    'archived context differs from historical sources');
}
export function receipt(value: unknown, current: DirectedSession): asserts value is DirectedReceipt {
  serializable(value); object(value); keys(value, ['request', 'result', 'revision', 'observationIds', 'eventIds']);
  request(value.request); integer(value.revision);
  check(value.revision <= current.revision && value.revision >= value.request.expectedRevision
    && value.request.epoch <= current.epoch, 'receipt sequence mismatch');
  object(value.result); keys(value.result, ['status', 'reason', 'position'], ['operation']);
  check(value.result.status === 'applied' || value.result.status === 'refused', 'invalid receipt outcome');
  text(value.result.reason); address(value.result.position);
  if (value.result.operation !== undefined) {
    operation(value.result.operation);
    check(value.result.operation.epoch <= value.request.epoch, 'receipt operation epoch mismatch');
  }
  for (const values of [value.observationIds, value.eventIds]) {
    list(values, DIRECTED_LIMITS.history); values.forEach(id);
    check(new Set(values).size === values.length, 'duplicate receipt evidence');
  }
}
