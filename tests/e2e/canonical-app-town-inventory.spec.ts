import { appGame, buy, capture, close, expect, freshTown, inventory, reserve, test } from './canonical-app-town-inventory.support';

test('fresh portal purchase -> explicit equip/unequip pack exclusion -> stash/withdraw -> return', async ({ page }, info) => {
  const { initial, town } = await freshTown(page);
  await page.getByRole('tab', { name: 'Auto Care', exact: true }).click();
  const autoEquip = page.getByRole('checkbox', { name: 'Auto equip', exact: true });
  await autoEquip.click(); await expect(autoEquip).not.toBeChecked();
  await expect.poll(async () => (await appGame(page)).inventoryPolicy?.autoEquip).toBe(false);
  const bought = await buy(page, 'Blacksmith', 'Rusty Sword', 8);
  const sword = bought.inventory.items.find(i => i.baseId === 'rusty-sword');
  if (!sword) throw Error('Vendor purchase did not retain a sword');
  expect(bought.inventory.gold).toBe(27); expect(bought.inventory.items).toHaveLength(3);
  // Vendor merging materializes the starter consumables' implicit one-unit quantities.
  expect(bought.inventory.items.filter(i => i.id !== sword.id)).toEqual(town.inventory.items.map(i => ({ ...i, quantity: 1 })));
  expect(bought.party).toEqual(initial.party);
  await inventory(page);
  const panel = page.getByRole('tabpanel', { name: 'Inventory', exact: true });
  await expect(panel).toContainText('Pack 3/36');
  const row = page.getByRole('article', { name: 'Rusty Sword', exact: true });
  await row.getByRole('button', { name: 'Equip', exact: true }).click();
  await expect.poll(async () => (await appGame(page)).party[0].equipment.weapon).toBe(sword.id);
  const equipped = await appGame(page);
  expect(equipped.inventory).toEqual(bought.inventory);
  expect(equipped.party[0]).toEqual({ ...bought.party[0], equipment: { ...bought.party[0].equipment, weapon: sword.id } });
  expect(equipped.party.slice(1)).toEqual(bought.party.slice(1));
  await expect(panel).toContainText('Pack 2/36');
  await expect(row.getByRole('button', { name: 'Equipped', exact: true })).toBeDisabled();
  await expect(row.getByRole('button', { name: 'Stash', exact: true })).toBeDisabled();
  await expect(row.getByRole('button', { name: /^Sell One/ })).toBeDisabled();
  await page.screenshot({ path: info.outputPath('equipped-pack-exclusion.png') });
  await page.getByRole('tab', { name: 'Equipment', exact: true }).click();
  await page.getByRole('button', { name: `Unequip Rusty Sword from ${initial.party[0].displayName}`, exact: true }).click();
  await expect.poll(async () => (await appGame(page)).party[0].equipment.weapon).toBeUndefined();
  await page.getByRole('tab', { name: 'Inventory', exact: true }).click();
  await expect(panel).toContainText('Pack 3/36');
  expect((await appGame(page)).party).toEqual(initial.party);
  await row.getByRole('button', { name: 'Stash', exact: true }).click();
  await expect.poll(async () => (await appGame(page)).stash.items).toEqual([sword]);
  const stashed = await appGame(page);
  expect(stashed.inventory.items).toEqual(bought.inventory.items.filter(i => i.id !== sword.id));
  expect(stashed.inventory.gold).toBe(27); await expect(panel).toContainText('Pack 2/36');
  await close(page);
  await page.getByRole('tab', { name: 'Storage', exact: true }).click();
  await page.locator('.town-stock-row').filter({ hasText: 'Rusty Sword' }).getByRole('button', { name: 'Withdraw', exact: true }).click();
  await expect.poll(async () => (await appGame(page)).stash.items).toEqual([]);
  const withdrawn = await appGame(page);
  expect(withdrawn.inventory).toEqual(bought.inventory); expect(withdrawn.party).toEqual(initial.party);
  await expect(page.getByRole('button', { name: 'Pack 3/36', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Dungeon', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Maze Battle', exact: true })).toBeVisible();
  const returned = await appGame(page);
  expect(returned.checkpoint.position).toEqual(initial.checkpoint.position);
  expect(returned.inventory).toEqual(withdrawn.inventory); expect(returned.quests).toEqual([]);
  await capture(page, info, 'before-equipment-reload');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Maze Battle', exact: true })).toBeVisible();
  const reloaded = await appGame(page);
  for (const field of ['party', 'inventory', 'stash', 'inventoryPolicy', 'quests'] as const) expect(reloaded[field]).toEqual(returned[field]);
  await expect(page.getByRole('button', { name: 'Portal (0)', exact: true })).toBeDisabled();
  await info.attach('equipment-roundtrip', { body: JSON.stringify({ initial, bought, equipped, stashed, withdrawn, returned, reloaded }), contentType: 'application/json' });
});

test('starting gold buys a real herb stack; selected amount and Sell All preserve exact gold and remaining units', async ({ page }, info) => {
  const { initial, town } = await freshTown(page), herb = town.inventory.items.find(i => i.baseId === 'health-herb');
  if (!herb) throw Error('Fresh inventory did not retain its health herb');
  for (let i = 0; i < 4; i++) await buy(page, 'Alchemist', 'Health Herb', 6);
  const stocked = await appGame(page), stack = stocked.inventory.items.find(i => i.id === herb.id);
  expect(stack).toEqual({ ...herb, quantity: 5 }); expect(stack?.value).toBe(8);
  expect(stocked.inventory.gold).toBe(11); expect(stocked.inventory.items).toHaveLength(2);
  expect(stocked.inventory.items.filter(i => i.id !== herb.id)).toEqual(town.inventory.items.filter(i => i.id !== herb.id).map(i => ({ ...i, quantity: 1 })));
  await inventory(page);
  const row = page.getByRole('article', { name: 'Health Herb', exact: true });
  await expect(page.getByRole('tabpanel', { name: 'Inventory', exact: true })).toContainText('Pack 2/36');
  await row.getByRole('slider', { name: 'Sell quantity for Health Herb', exact: true }).fill('2');
  await row.getByRole('button', { name: 'Sell 2 8g', exact: true }).click();
  await expect.poll(async () => (await appGame(page)).inventory.gold).toBe(19);
  const partial = await appGame(page);
  expect(partial.inventory.items.find(i => i.id === herb.id)).toEqual({ ...herb, quantity: 3 });
  expect(partial.inventory.items.filter(i => i.id !== herb.id)).toEqual(stocked.inventory.items.filter(i => i.id !== herb.id));
  await expect(row.getByRole('slider', { name: 'Sell quantity for Health Herb', exact: true })).toHaveAttribute('max', '3');
  await page.screenshot({ path: info.outputPath('partial-stack-sale.png') });
  await row.getByRole('button', { name: 'Sell All (3) 12g', exact: true }).click();
  await expect.poll(async () => (await appGame(page)).inventory.gold).toBe(31);
  await expect(row).toHaveCount(0);
  const sold = await appGame(page);
  expect(sold.inventory.items).toEqual(stocked.inventory.items.filter(i => i.id !== herb.id));
  expect(sold.party).toEqual(initial.party); expect(sold.stash).toEqual(town.stash); expect(sold.quests).toEqual([]);
  await expect(page.getByRole('tabpanel', { name: 'Inventory', exact: true })).toContainText('Pack 1/36');
  await close(page); await capture(page, info, 'before-sale-reload');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Town', exact: true })).toBeVisible();
  expect((await appGame(page)).inventory).toEqual(sold.inventory);
  await inventory(page);
  await expect(page.getByRole('article', { name: 'Health Herb', exact: true })).toHaveCount(0);
  await info.attach('stack-sale-roundtrip', { body: JSON.stringify({ initial, stocked, partial, sold, reloaded: await appGame(page) }), contentType: 'application/json' });
});

test('town and inventory reserve panels persist one canonical policy across reload and dungeon return', async ({ page }, info) => {
  const { initial, town } = await freshTown(page);
  await page.getByRole('tab', { name: 'Auto Care', exact: true }).click();
  await reserve(page, 'Health', 7); await reserve(page, 'Mana', 4); await reserve(page, 'Portal', 3);
  const townPolicy = await appGame(page);
  expect(townPolicy.inventoryPolicy).toEqual({ ...town.inventoryPolicy, healthReserve: 7, manaReserve: 4, portalReserve: 3 });
  await inventory(page);
  await page.getByText('Inventory care', { exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Characters', exact: true });
  for (const [name, value] of [['Health', '7'], ['Mana', '4'], ['Portal', '3']] as const)
    await expect(dialog.getByLabel(`${name} reserve`, { exact: true })).toHaveValue(value);
  await reserve(page, 'Health', 0); await reserve(page, 'Mana', 20); await reserve(page, 'Portal', 5);
  const updated = await appGame(page);
  expect(updated.inventoryPolicy).toEqual({ ...town.inventoryPolicy, healthReserve: 0, manaReserve: 20, portalReserve: 5 });
  expect(updated.inventory).toEqual(town.inventory); expect(updated.stash).toEqual(town.stash);
  expect(updated.party).toEqual(initial.party); expect(updated.quests).toEqual([]);
  await close(page); await capture(page, info, 'before-policy-reload');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Town', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Auto Care', exact: true }).click();
  for (const [name, value] of [['Health', '0'], ['Mana', '20'], ['Portal', '5']] as const)
    await expect(page.getByLabel(`${name} reserve`, { exact: true })).toHaveValue(value);
  await page.screenshot({ path: info.outputPath('persisted-town-policy.png') });
  await inventory(page); await page.getByText('Inventory care', { exact: true }).click();
  for (const [name, value] of [['Health', '0'], ['Mana', '20'], ['Portal', '5']] as const)
    await expect(dialog.getByLabel(`${name} reserve`, { exact: true })).toHaveValue(value);
  await close(page);
  await page.getByRole('button', { name: 'Dungeon', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Maze Battle', exact: true })).toBeVisible();
  const returned = await appGame(page);
  expect(returned.inventoryPolicy).toEqual(updated.inventoryPolicy); expect(returned.mode).toBe('manual');
  expect(returned.inventory).toEqual(town.inventory); expect(returned.checkpoint.position).toEqual(initial.checkpoint.position);
  await info.attach('policy-roundtrip', { body: JSON.stringify({ initial, townPolicy, updated, returned }), contentType: 'application/json' });
});
